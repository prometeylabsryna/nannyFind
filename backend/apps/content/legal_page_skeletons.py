FILL = '<p><strong>[ЗАПОВНИТИ: {label}]</strong> {hint}</p>'


def _h(text: str) -> str:
    return HINT.format(text=text)


def _f(label: str, hint: str) -> str:
    return FILL.format(label=label, hint=hint)


def _section(title: str, *parts: str) -> str:
    return f'<section class="legal-section"><h2>{title}</h2>{"".join(parts)}</section>'


